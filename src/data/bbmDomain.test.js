import assert from 'node:assert/strict'
import { bbmLocationLabel, bbmPlaceOptions, bbmReportDate, bbmVehicleLabel, calculateBbm, monthDays, validateBbm, purchaseTotal } from './bbmDomain.js'
assert.deepEqual(bbmPlaceOptions('').map((option) => option.value), ['SPBU', 'Eceran'])
assert.deepEqual(bbmPlaceOptions('spbu').map((option) => option.value), ['SPBU', 'Eceran'])
assert.deepEqual(bbmPlaceOptions('Pertashop').map((option) => option.value), ['SPBU', 'Eceran', 'Pertashop'])
assert.equal(bbmLocationLabel({ location_name: 'Sempalit', location_type: 'KANTOR_JAGA' }), 'KJ Sempalit')
assert.equal(bbmLocationLabel({ location_name: 'ULP Pemangkat', location_type: 'UNIT_OFFICE' }), 'ULP Pemangkat')
assert.equal(bbmLocationLabel({}), '')
assert.equal(bbmVehicleLabel({ plate_display: 'KB 1382 AX', label: 'Roda 4', location_name: 'Sempalit', location_type: 'KANTOR_JAGA' }), 'KB 1382 AX · Roda 4 · KJ Sempalit')
assert.equal(bbmVehicleLabel({ plate_display: '', label: 'Roda 2' }), 'Nopol belum diisi · Roda 2')
assert.equal(monthDays('2024-02').length, 29)
assert.equal(monthDays('2026-02').length, 28)
const fullMonth = (month) => monthDays(month).map((date, index) => ({ date, end: 100 + index, photo: `odo-${index}`, purchases: [] }))
assert.equal(bbmReportDate('2026-11', fullMonth('2026-11'), '2026-11-30'), '2026-11-30')
assert.equal(bbmReportDate('2026-11', fullMonth('2026-11'), '2026-11-29'), null)
assert.equal(bbmReportDate('2026-11', fullMonth('2026-11').slice(0, -1), '2026-12-01'), null)
assert.equal(bbmReportDate('2026-11', fullMonth('2026-11').map((row, index) => index === 10 ? { ...row, photo: '' } : row), '2026-12-01'), null)
assert.equal(bbmReportDate('2026-11', fullMonth('2026-11').map((row, index) => index === 10 ? { ...row, end: '' } : row), '2026-12-01'), null)
assert.equal(bbmReportDate('2028-02', fullMonth('2028-02'), '2028-02-29'), '2028-02-29')
assert.equal(bbmReportDate('2026-12', fullMonth('2026-12'), '2027-01-31'), '2026-12-31')
assert.equal(bbmReportDate('2026-10', [], '2026-12-01'), null)
const rows = [
  { date: '2026-10-01', end: 120, photo: 'odo', purchases: [] },
  { date: '2026-10-02', end: 150, photo: 'odo2', purchases: [{ fuel: 'Pertalite', liters: 2.5, price: 10000, photo: 'receipt' }, { fuel: 'Pertamax', liters: 1, price: 12000, photo: 'receipt2' }] },
]
const summary = calculateBbm('2026-10', rows, 0, { date: '2026-09-30', end: 100 })
assert.equal(summary.km, 50)
assert.equal(summary.total, 37000)
assert.equal(summary.liters, 3.5)
assert.equal(summary.days[1].start, 120)
assert.equal(summary.recorded, 2)
assert.equal(summary.gaps, 0)
assert.equal(purchaseTotal({ liters: 0.333, price: 10000 }), 3330)
assert.equal(calculateBbm('2026-10', [rows[1]], 100, null).ratio, 50 / 3.5)
assert.equal(calculateBbm('2026-10', [rows[0]], '', null).days[0].distance, null)
assert.equal(calculateBbm('2026-10', [rows[1]], 100, { date: '2026-09-30', end: 100 }).gaps, 1)
validateBbm(rows, '', { end: 100 }, '2026-11-01')
assert.throws(() => validateBbm(rows, '', null), /stand awal/)
assert.throws(() => validateBbm([{ ...rows[0], end: 99 }], 100, null), /stand akhir/)
assert.throws(() => validateBbm([{ ...rows[0], photo: '' }], 100, null), /foto odometer/)
assert.throws(() => validateBbm([{ ...rows[1], purchases: [{ fuel: 'Pertalite', liters: 1, price: 10000 }] }], 100, null), /foto struk/)
assert.throws(() => validateBbm(rows, 100, null, '2026-09-30'), /belum dapat/)
assert.equal(calculateBbm('2026-10', [{ ...rows[0], end: 125 }, rows[1]], 100, null).days[1].distance, 25)
console.log('BBM domain: dates, carryover, corrections, multiple purchases, totals, missing evidence passed.')
